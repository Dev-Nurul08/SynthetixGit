/**
 * Render text string into a 52x7 grid with level 4 intensity
 */
export function textToGrid52x7(text: string): number[][] {
  // Initialize 52 columns x 7 rows with 0
  const grid: number[][] = Array.from({ length: 52 }, () => Array(7).fill(0));
  const chars = text.toUpperCase().split('');

  let currentCol = 2; // Start with 2 empty columns padding

  for (const ch of chars) {
    const glyph = FONT_5X7[ch] || FONT_5X7[' '];
    const glyphWidth = glyph[0].length; // 5

    if (currentCol + glyphWidth > 50) break; // Out of bounds

    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < glyphWidth; c++) {
        if (glyph[r][c] === 1) {
          grid[currentCol + c][r] = 4; // intensity level 4
        }
      }
    }
    currentCol += glyphWidth + 1; // 1 column spacing between letters
  }

  return grid;
}
